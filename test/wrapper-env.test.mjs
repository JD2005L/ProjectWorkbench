// The dashboard rewrites /etc/project-workbench/claude-wrapper.env on every Settings save. It owns four keys;
// whatever else an operator set there (PW_REMOTE_CONTROL=false, PW_CLAUDE_RESTART=off) has to survive the save,
// or the setting silently goes back to its default.
import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderWrapperEnv, WRAPPER_ENV_OWNED } from '../app/wrapper-env.js';

const SERVER = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'app', 'server.js');
const settings = { mcpMode: 'isolated', permissionMode: 'skip', emptyMcpPath: '/etc/project-workbench/empty-mcp.json' };
const OWNED_BODY = [
  '# Generated by Project Workbench Setup Wizard',
  'PW_SHARED_MEMORY=/opt/project-workbench/memory',
  'PW_MCP_MODE=isolated',
  'PW_MCP_CONFIG=/etc/project-workbench/empty-mcp.json',
  'PW_PERMISSION_MODE=skip',
];

test('a new file is exactly what the dashboard always wrote', () => {
  assert.equal(renderWrapperEnv({ ...settings, current: '' }), `${OWNED_BODY.join('\n')}\n`);
  assert.equal(renderWrapperEnv({ ...settings, mcpMode: 'bogus' }).split('\n')[2], 'PW_MCP_MODE=inherit');
});

test('a Settings save keeps what an operator set and rewrites only the keys it owns', () => {
  const current = [
    '# an operator comment',
    'PW_MCP_MODE=custom',
    'PW_MCP_CONFIG=/etc/project-workbench/team-mcp.json',
    'PW_REMOTE_CONTROL=false',
    'export PW_CLAUDE_RESTART=off',
    '',
  ].join('\n');
  const out = renderWrapperEnv({ ...settings, current });
  assert.equal(out, `${[...OWNED_BODY, 'PW_REMOTE_CONTROL=false', 'export PW_CLAUDE_RESTART=off'].join('\n')}\n`);
  assert.equal(renderWrapperEnv({ ...settings, current: out }), out, 'saving again changes nothing');
  assert.deepEqual(WRAPPER_ENV_OWNED, ['PW_SHARED_MEMORY', 'PW_MCP_MODE', 'PW_MCP_CONFIG', 'PW_PERMISSION_MODE']);
});

test('the dashboard writes the file through renderWrapperEnv, reading what is there first', () => {
  const src = fs.readFileSync(SERVER, 'utf8');
  const fn = src.slice(src.indexOf('async function syncWrapperEnv('), src.indexOf('\n}\n', src.indexOf('async function syncWrapperEnv(')));
  assert.match(fn, /fs\.readFile\(wrapperEnvPath/);
  assert.match(fn, /renderWrapperEnv\(\{[^}]*current/);
});
