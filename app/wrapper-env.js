// /etc/project-workbench/claude-wrapper.env is the instance policy /usr/local/bin/claude sources before it starts
// Claude Code. The dashboard owns four of its keys and writes them from its settings. Every other assignment in
// the file (PW_REMOTE_CONTROL, PW_CLAUDE_RESTART, anything an operator added) is carried over unchanged: the
// file used to be rewritten from scratch, so one Settings save quietly put those back to their defaults.
export const WRAPPER_ENV_OWNED = Object.freeze(['PW_SHARED_MEMORY', 'PW_MCP_MODE', 'PW_MCP_CONFIG', 'PW_PERMISSION_MODE']);
const ASSIGNMENT = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)=/;
const MCP_MODES = ['inherit', 'isolated', 'custom'];

export function renderWrapperEnv({ mcpMode, permissionMode, emptyMcpPath, current = '' }) {
  const owned = new Set(WRAPPER_ENV_OWNED);
  const kept = String(current).split('\n').filter((line) => {
    const m = ASSIGNMENT.exec(line);
    return !!m && !owned.has(m[1]);
  });
  return [
    '# Generated by Project Workbench Setup Wizard',
    'PW_SHARED_MEMORY=/opt/project-workbench/memory',
    `PW_MCP_MODE=${MCP_MODES.includes(mcpMode) ? mcpMode : 'inherit'}`,
    `PW_MCP_CONFIG=${emptyMcpPath}`,
    `PW_PERMISSION_MODE=${permissionMode}`,
    ...kept,
    '',
  ].join('\n');
}
